    def test_19_unsafe_footer_mutation_cannot_claim_safe(self):
        _, source, exports = self.tree('unsafe-footer')
        os.symlink('originals/retained.partial', source / 'unsafe-link')
        result = LIFE.collect_tree(source, exports, quiescent=True)
        self.assertFalse(result['source_tree_complete'])
        raw = (exports / 'fixture.neutral').read_bytes()
        cursor = len(LIFE.MAGIC)
        while cursor < len(raw):
            offset = cursor
            size = LIFE.struct.unpack('>I', raw[cursor:cursor + 4])[0]
            row = json.loads(raw[cursor + 4:cursor + 4 + size])
            cursor += 4 + size
            if row.get('end') is True:
                self.assertFalse(row['safe'])
                row['safe'] = True
                changed = (json.dumps(row, sort_keys=True, separators=(',', ':')) + '\n').encode('ascii')
                mutant = raw[:offset] + LIFE.struct.pack('>I', len(changed)) + changed
                break
            if row['kind'] == 'regular' and row['unsafe'] is None:
                cursor += row['data_bytes']
        else:
            self.fail('actual neutral footer missing')
        path = exports / 'mutated-safe-footer.neutral'
        file_bytes(path, mutant)
        with self.assertRaises(RuntimeError):
            LIFE.verify_neutral(path)
        self.assertFalse(LIFE.verify_neutral(exports / 'fixture.neutral')['safe'])

