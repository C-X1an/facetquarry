    def test_03_every_distinct_close_attempted_and_primary_retained(self):
        # A pure descriptor-ownership control, not simulated POSIX integration.
        attempted = []

        def close(fd):
            attempted.append(fd)
            if fd in (7001, 7003):
                raise OSError(5, 'deliberate pure close error')

        caught = None
        with mock.patch.object(LIFE.os, 'close', close):
            try:
                try:
                    raise ValueError('original failure must survive')
                finally:
                    LIFE.close_owned(7001, 7002, 7001, None, 7003)
            except BaseExceptionGroup as error:
                caught = error
        self.assertEqual(attempted, [7001, 7002, 7003])
        self.assertIsNotNone(caught)
        self.assertEqual([type(error).__name__ for error in caught.exceptions],
                         ['ValueError', 'OSError', 'OSError'])

