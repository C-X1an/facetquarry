class BoundedResult(unittest.TextTestResult):
    def _exc_info_to_string(self, error, test):
        text = super()._exc_info_to_string(error, test)
        return text if len(text) <= 16384 else text[:8192] + '\n[display bounded; failure retained]\n' + text[-8192:]


def main():
    global LIFE, ROOT, PYTHON, LIFE_PATH
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--test-root', type=Path, required=True)
    parser.add_argument('--lifecycle-sha256', required=True)
    parser.add_argument('--python', required=True)
    parser.add_argument('--python-bytes', type=int, required=True)
    parser.add_argument('--python-sha256', required=True)
    args = parser.parse_args()
    LIFE_PATH = Path(__file__).absolute().parent / 'scientific_posix_lifecycle.py'
    # The external wrapper also pins this control file and the complete manifest.
    with open(LIFE_PATH, 'rb') as stream:
        raw = stream.read(128000)
        if stream.read(1):
            raise RuntimeError('CONTROL_SOURCE_BYTE_BOUND')
    if hashlib.sha256(raw).hexdigest() != args.lifecycle_sha256:
        raise RuntimeError('INDEPENDENT_LIFECYCLE_SOURCE_PIN_REQUIRED')
    LIFE = SimpleNamespace(**runpy.run_path(str(LIFE_PATH), run_name='source_only_control_import'))
    LIFE.require_linux()
    if os.geteuid() == 0:
        raise RuntimeError('CONTROLS_REQUIRE_UNPRIVILEGED_UID')
    ROOT = LIFE.explicit_path(args.test_root)
    PYTHON = LIFE.pin_runtime({'path': args.python, 'bytes': args.python_bytes, 'sha256': args.python_sha256})
    if Path(sys.executable) != Path(PYTHON):
        raise RuntimeError('EXACT_PINNED_CONTROL_INTERPRETER_REQUIRED')
    os.umask(0o077)
    resource.setrlimit(resource.RLIMIT_AS, (LIFE.MEMORY_BYTES, LIFE.MEMORY_BYTES))
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    LIFE.new_dir(ROOT)
    suite = unittest.defaultTestLoader.loadTestsFromTestCase(LifecycleControls)
    result = unittest.TextTestRunner(verbosity=2, resultclass=BoundedResult).run(suite)
    # This is the control command's actual outcome, never an SPI result/seal.
    return 0 if result.wasSuccessful() and result.testsRun == 22 and not result.skipped else 1


if __name__ == '__main__':
    raise SystemExit(main())
