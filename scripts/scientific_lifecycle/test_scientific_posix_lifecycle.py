def file_bytes(path, raw):
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
    try:
        LIFE.write_all(fd, raw)
        os.fsync(fd)
    finally:
        LIFE.close_owned(fd)


def direct_inventory(root):
    # Independent small-fixture inventory, never following a link.
    answer = {}
    pending = [root]
    while pending:
        current = pending.pop()
        with os.scandir(current) as entries:
            for entry in entries:
                relative = os.fsencode(os.path.relpath(entry.path, root))
                info = entry.stat(follow_symlinks=False)
                if entry.is_dir(follow_symlinks=False):
                    answer[relative] = ('directory', None)
                    pending.append(Path(entry.path))
                elif entry.is_file(follow_symlinks=False):
                    with open(entry.path, 'rb') as stream:
                        raw = stream.read(1 << 20)
                        if stream.read(1):
                            raise RuntimeError('CONTROL_FIXTURE_FILE_BOUND')
                    answer[relative] = ('regular', hashlib.sha256(raw).hexdigest())
                else:
                    answer[relative] = ('unsafe', info.st_mode)
    return answer


class LifecycleControls(unittest.TestCase):
    def case(self, name):
        root = ROOT / name
        LIFE.new_dir(root)
        return root

    def tree(self, name):
        case = self.case(name)
        source, exports = case / 'fixture', case / 'exports'
        LIFE.new_dir(source)
        LIFE.new_dir(exports)
        directories = ['originals', 'staging', 'packed', 'catalogs', 'metadata', 'unknown',
                       'tails', 'normal-envelope', 'failure-envelope', 'internal-copy']
        for item in directories:
            LIFE.new_dir(source / item)
            file_bytes(source / item / 'retained.partial', b'PAYLOAD-' + item.encode('ascii') + b'\x00\xff\n')
        file_bytes(source / 'catalogs' / 'catalog.final', b'actual fixture bytes, not a protocol catalog\n')
        file_bytes(source / 'empty', b'')
        return case, source, exports

