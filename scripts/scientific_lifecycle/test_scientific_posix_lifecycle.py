    def payload(self, name, code, *, seconds=10, file_limit=None):
        case = self.case(name)
        source, exports, logs = case / 'fixture', case / 'exports', case / 'logs'
        for path in (source, exports, logs):
            LIFE.new_dir(path)
        command = [PYTHON, '-I', '-S', '-B', '-c', code, str(source)]
        options = {} if file_limit is None else {'file_limit': file_limit}
        result = LIFE.run_process(command, source, logs, seconds=seconds, **options)
        collection = LIFE.collect_tree(source, exports, quiescent=result['quiescent'])
        return result, collection, source, logs

